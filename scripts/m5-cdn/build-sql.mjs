// Generates the Owner-run SQL from Phase 0 output: 002 (normalization with the exact exclusion list) and 004 (targeted
// tile repair for CONFIRMED candidates only). Confirmed = old object missing, `.original` sibling present in the storage
// listing, sibling delivered by the pull zone (HTTP 200, image/*), and provenance evidence (same product already references
// the sibling, or the file code is in the product SKU/slug). Only column fields are repaired; HTML occurrences are reported.
import { readFileSync, writeFileSync } from 'node:fs'
import { OLD_PREFIX, NEW_PREFIX } from './phase0.mjs'

export const sqlString = (v) => `'${String(v).replace(/'/g, "''")}'`

export function buildNormalization(template, { excluded, phase0, maxStartBytes }) {
  for (const u of excluded) if (!u.startsWith(OLD_PREFIX) || /[\u0000-\u001f]/.test(u)) throw new Error(`bad excluded url: ${u}`)
  const list = excluded.length ? excluded.map((u) => `  ${sqlString(u)}`).join(',\n') : ''
  return template.replace('__PHASE0__', phase0).replace('__MAX_START_BYTES__', String(maxStartBytes)).replace('__EXCLUDED__', list)
}

export function confirmTiles(tiles, headRows) {
  const head = new Map(headRows.map(([status, type, , url]) => [url, { status: String(status), type: String(type) }]))
  const confirmed = [], rejected = []
  for (const t of tiles) {
    const h = head.get(NEW_PREFIX + t.sibling)
    const fixable = t.rows.filter(([tbl, , col]) => (tbl === 'product_images' && col === 'image_url') || (tbl === 'products' && col === 'image_main_url'))
    const reasons = []
    if (!h || h.status !== '200' || !h.type.startsWith('image/')) reasons.push(`sibling_delivery:${h ? `${h.status} ${h.type}` : 'unchecked'}`)
    if (!t.evidence.length) reasons.push('no_provenance')
    if (!fixable.length) reasons.push('html_only')
    if (reasons.length) rejected.push({ ...t, reasons }); else confirmed.push({ ...t, fixable, htmlRows: t.rows.length - fixable.length })
  }
  return { confirmed, rejected }
}

export function buildTileRepair(confirmed, phase0) {
  const values = confirmed.flatMap((t) => t.fixable.map(([tbl, pk, col]) =>
    `  (${sqlString(tbl)}, ${Number(pk)}, ${sqlString(col)}, ${sqlString(OLD_PREFIX + t.path)}, ${sqlString(NEW_PREFIX + t.sibling)})`))
  return `-- M5 PRODUCTION (project bonxyxluzlxfkdetryoo): targeted repair of broken tile images (GENERATED by
-- scripts/m5-cdn/build-sql.mjs from Phase 0 ${phase0}; do not edit by hand). ${values.length} column values, ${confirmed.length} files.
-- Each row: the stored URL points to an object that is NOT in the storage zone; the exact sibling "<name>.original.<ext>"
-- IS in the zone, is delivered as an image by the pull zone, and has provenance evidence (see the Phase 0 report).
-- Updates only if the stored value is still exactly the broken URL; ledger dpg_control.m5_tile_ledger keeps old/new values.
-- Rollback (only rows still equal to the repaired value):
--   update dpg_app.product_images t set image_url = l.old_value from dpg_control.m5_tile_ledger l
--     where l.tbl = 'product_images' and t.id = l.pk and t.image_url = l.new_value;
--   update dpg_app.products t set image_main_url = l.old_value, version = t.version + 1 from dpg_control.m5_tile_ledger l
--     where l.tbl = 'products' and t.id = l.pk and t.image_main_url = l.new_value;
begin;
set local lock_timeout = '5s';
do $$ begin
  if not exists (select 1 from dpg_control.target_contract where project_name = 'dongphugia-runtime' and production_writes_allowed)
     or (select count(*) from dpg_app.products) < 17000 then raise exception 'M5_TILE_GUARD_FAILED: not the Production project'; end if;
end $$;
create table if not exists dpg_control.m5_tile_ledger (
  tbl text not null, pk integer not null, col text not null, old_value text not null, new_value text not null,
  product_id integer, repaired_at timestamptz not null default now(), primary key (tbl, pk, col));
alter table dpg_control.m5_tile_ledger enable row level security;
revoke all on dpg_control.m5_tile_ledger from public;
create temp table m5_tile_fix (tbl text, pk integer, col text, old_url text, new_url text) on commit drop;
insert into m5_tile_fix values
${values.join(',\n') || "  ('none', 0, 'none', 'none', 'none')"};
with u as (update dpg_app.product_images t set image_url = f.new_url from m5_tile_fix f
           where f.tbl = 'product_images' and f.col = 'image_url' and t.id = f.pk and t.image_url = f.old_url
           returning t.id, t.product_id, f.old_url, f.new_url)
insert into dpg_control.m5_tile_ledger (tbl, pk, col, old_value, new_value, product_id)
select 'product_images', id, 'image_url', old_url, new_url, product_id from u on conflict do nothing;
with u as (update dpg_app.products t set image_main_url = f.new_url, version = t.version + 1 from m5_tile_fix f
           where f.tbl = 'products' and f.col = 'image_main_url' and t.id = f.pk and t.image_main_url = f.old_url
           returning t.id, f.old_url, f.new_url)
insert into dpg_control.m5_tile_ledger (tbl, pk, col, old_value, new_value, product_id)
select 'products', id, 'image_main_url', old_url, new_url, id from u on conflict do nothing;
update dpg_app.products p set version = p.version + 1
where p.id in (select product_id from dpg_control.m5_tile_ledger where tbl = 'product_images' and repaired_at = now())
  and p.id not in (select pk from dpg_control.m5_tile_ledger where tbl = 'products' and repaired_at = now());
select tbl || '.' || col as field, count(*) as repaired from dpg_control.m5_tile_ledger where repaired_at = now() group by 1
union all select 'expected', ${values.length};
commit;
`
}

if (import.meta.url === `file://${process.argv[1]}`) {
  const [phase0Dir, phase0Id, maxStartBytes, outDir] = process.argv.slice(2)
  const excluded = readFileSync(`${phase0Dir}/excluded-urls.txt`, 'utf8').split('\n').filter(Boolean)
  const template = readFileSync(new URL('./002.template.sql', import.meta.url), 'utf8')
  writeFileSync(`${outDir}/002_cdn_normalization.sql`, buildNormalization(template, { excluded, phase0: phase0Id, maxStartBytes: Number(maxStartBytes) }))
  const tiles = JSON.parse(readFileSync(`${phase0Dir}/tiles.json`, 'utf8'))
  const headRows = readFileSync(`${phase0Dir}/head.tsv`, 'utf8').split('\n').filter(Boolean).map((l) => l.split('\t'))
  const { confirmed, rejected } = confirmTiles(tiles, headRows)
  writeFileSync(`${outDir}/004_tile_image_repair.sql`, buildTileRepair(confirmed, phase0Id))
  writeFileSync(`${phase0Dir}/tiles-decision.json`, JSON.stringify({ confirmed: confirmed.map((t) => ({ path: t.path, sibling: t.sibling, evidence: t.evidence, fixable: t.fixable.length, htmlRows: t.htmlRows })), rejected: rejected.map((t) => ({ path: t.path, reasons: t.reasons, rows: t.rows.length })) }, null, 2))
  console.log(`M5_CDN_BUILD excluded=${excluded.length} tiles_confirmed=${confirmed.length} tile_values=${confirmed.reduce((a, t) => a + t.fixable.length, 0)} tiles_rejected=${rejected.length} rejected_reasons=${JSON.stringify(rejected.reduce((a, t) => { for (const r of t.reasons) { const k = r.split(':')[0]; a[k] = (a[k] ?? 0) + 1 } return a }, {}))}`)
}
